test("a company's words are its resolved mention and label, each whole", () => {
  const hpe = { kind: "issuer", id: "hpe" } as const;
  const table: Array<[string, Parameters<typeof turnScenarioAsk>[1], ReturnType<typeof turnScenarioAsk>]> = [
    ["HPE enterprise value bear 8x base 10x bull 12x", [{ mention: "HPE", resolution: { status: "resolved", subject_ref: hpe, label: "Hewlett Packard Enterprise" } }], invalid(3)],
    ["Hewlett Packard Enterprise's bear 8x, base 10x, bull 12x", [{ mention: "HPE", resolution: { status: "resolved", subject_ref: hpe, label: "Hewlett Packard Enterprise" } }], ask(3, { bear: "8", base: "10", bull: "12" })],
    ["MSFT bear 20x, base 25x, bull 30x", [{ mention: "MSFT", resolution: { status: "not_found" } }], invalid(3)],
    ["Is the bull 30x too aggressive?", [{ mention: "AAPL", resolution: { status: "resolved", subject_ref: hpe, label: "Apple Inc." } }], null],
  ];
  assert.deepEqual(table.map(([text, subjects]) => [text, subjects, turnScenarioAsk(text, subjects)]), table);
});

test("a long message is read without backtracking blowup", { timeout: 5_000 }, () => {
  const table: Array<[string, ReturnType<typeof readScenarioAsk>]> = [
    ["AAPL P/E " + "1".repeat(40) + "a", null],
    ["AAPL P/E " + "1/".repeat(20_000) + "a", null],
    ["AAPL P/E 20, 25" + " ".repeat(20_000) + "a", null],
    ["AAPL P/E 20, 25 " + " ".repeat(20_000) + "and", null],
    ["bear" + " - ".repeat(20_000) + "a", null],
    ["bear/base/bull" + " ".repeat(20_000) + "a", null],
    ["bear" + " ".repeat(20_000) + "a", null],
    ["bear/".repeat(20_000) + "a", null],
    ["bear/".repeat(20_000) + "20x", invalid(1)],
  ];
  assert.deepEqual(table.map(([text]) => [text.slice(0, 20), readScenarioAsk(text, COMPANY)]), table.map(([text, expected]) => [text.slice(0, 20), expected]));
});
